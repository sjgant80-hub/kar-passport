#!/usr/bin/env node
// tools/template.mjs: src/template62.mjs is SYMBEYOND's v6.2 template, line for line, as a module the codec and the page
// import (so the renderer's fixed text is the protocol's own words, not a retyping). --check proves it still is.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const ROOT = join(import.meta.dirname, '..');
const SRC = 'vendor/symbfer/symbeyond/SYMB-FER_v6.2_PROTOCOL_2026-06-01_1015H.txt';
const lines = readFileSync(join(ROOT, SRC), 'utf8').split('\n');
const out = '// src/template62.mjs: GENERATED by tools/template.mjs from ' + SRC + ' (SYMBEYOND/SYMB-FER 7370e7d, MIT).\n' +
  '// SYMB-FER, SYMBEYOND AI LLC, 2026. Line n of the template is T62[n - 1]. Never edit by hand.\n' +
  'export const T62 = Object.freeze(' + JSON.stringify(lines, null, 0).replace(/","/g, '",\n "') + ');\n';
const target = join(ROOT, 'src', 'template62.mjs');
if (process.argv[2] === '--check') {
  if (readFileSync(target, 'utf8') !== out) { console.error('src/template62.mjs is not the vendored template'); process.exit(1); }
  console.log('src/template62.mjs = the vendored v6.2 template, ' + lines.length + ' lines');
} else { writeFileSync(target, out); console.log('wrote src/template62.mjs, ' + lines.length + ' lines'); }
